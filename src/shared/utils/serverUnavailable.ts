/**
 * Сообщение по умолчанию, показываемое пользователю когда защищённая страница
 * не смогла выполнить guard-запрос `/auth/me` из-за ошибки сервера (5xx) или
 * сети. Текст специально нейтральный — мы не разлогиниваем пользователя и не
 * утверждаем, что его сессия испорчена; проблема на стороне бэкенда.
 */
const DEFAULT_MESSAGE = 'Сервер временно недоступен. Попробуйте обновить страницу позже.';

/**
 * Рендерит в указанный root минималистичный плейсхолдер «сервер недоступен».
 * Используется guard'ами защищённых страниц, когда `/auth/me` вернул 5xx или
 * упал по сети — в этом случае нельзя считать, что пользователь разлогинен,
 * и нельзя редиректить на /sign, но и пустой `root` оставлять тоже нельзя.
 *
 * Текст сообщения экранируется через textContent (а не innerHTML) — XSS-безопасно.
 * @param root - корневой элемент SPA (обычно `#root`)
 * @param message - опциональный пользовательский текст; если не задан, используется
 *                  стандартное сообщение про временную недоступность сервера
 */
export function renderServerUnavailable(root: HTMLElement, message?: string): void {
    const wrapper = document.createElement('div');
    wrapper.className = 'server-unavailable';
    wrapper.setAttribute('role', 'alert');
    wrapper.textContent = message ?? DEFAULT_MESSAGE;
    root.appendChild(wrapper);
}
